package com.example.data

import kotlinx.coroutines.flow.Flow
import java.time.LocalDate
import java.time.format.DateTimeFormatter

class TransactionRepository(private val transactionDao: TransactionDao) {

    val allTransactions: Flow<List<TransactionEntity>> = transactionDao.getAllTransactions()

    fun getTransactionsByDateRange(startDate: String, endDate: String): Flow<List<TransactionEntity>> {
        return transactionDao.getTransactionsByDateRange(startDate, endDate)
    }

    suspend fun insert(transaction: TransactionEntity): Long {
        return transactionDao.insertTransaction(transaction)
    }

    suspend fun update(transaction: TransactionEntity) {
        transactionDao.updateTransaction(transaction)
    }

    suspend fun delete(transaction: TransactionEntity) {
        transactionDao.deleteTransaction(transaction)
    }

    suspend fun deleteById(id: Long) {
        transactionDao.deleteById(id)
    }

    suspend fun checkAndProcessRecurringTransactions() {
        val recurringList = transactionDao.getRecurringTransactions()
        if (recurringList.isEmpty()) return

        val today = LocalDate.now()
        val currentYearMonth = "%04d-%02d".format(today.year, today.monthValue)

        for (item in recurringList) {
            // Check if this recurring item has already generated an entry for current month
            if (item.lastGeneratedMonth != currentYearMonth && today.dayOfMonth >= item.recurringDayOfMonth) {
                val day = item.recurringDayOfMonth.coerceAtMost(today.lengthOfMonth())
                val targetDateStr = "%04d-%02d-%02d".format(today.year, today.monthValue, day)

                // Only generate if not already the exact original item's date
                if (item.date != targetDateStr) {
                    val autoGeneratedEntry = TransactionEntity(
                        type = item.type,
                        amount = item.amount,
                        note = "${item.note} (মাসিক স্বয়ংক্রিয়)",
                        category = item.category,
                        date = targetDateStr,
                        paymentMethod = item.paymentMethod,
                        isRecurring = false
                    )
                    transactionDao.insertTransaction(autoGeneratedEntry)
                }

                // Update template's lastGeneratedMonth
                transactionDao.updateTransaction(
                    item.copy(lastGeneratedMonth = currentYearMonth)
                )
            }
        }
    }

